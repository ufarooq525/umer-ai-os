import { mkdir, writeFile, access } from 'node:fs/promises';
import { join } from 'node:path';
import type { ResolvedProject } from './types.js';
import type { QaAuditItem, QaAuditReport } from './qa-audit.js';
import { collectQaRepoSignals, evaluateQaChecks, type QaCheckResult } from './qa-verify.js';
import { mergeQaRunIntoChecks, runQaSuites } from './qa-run.js';
import type { QaApplyFileChange, QaApplyResult } from './qa-result-types.js';

export type { QaApplyFileChange, QaApplyResult } from './qa-result-types.js';

async function exists(path: string): Promise<boolean> {
  try {
    await access(path);
    return true;
  } catch {
    return false;
  }
}

async function ensureDir(path: string): Promise<void> {
  await mkdir(path, { recursive: true });
}

function umerQaDir(projectRoot: string): string {
  return join(projectRoot, '.umer', 'qa');
}

async function verifyExisting(
  project: ResolvedProject,
): Promise<{ verified: string[]; notes: QaApplyFileChange[] }> {
  const verified: string[] = [];
  const notes: QaApplyFileChange[] = [];
  const root = project.absolutePath;

  const candidates: Array<{ rel: string; label: string }> = [
    { rel: 'tests', label: 'tests/ directory' },
    { rel: 'phpunit.xml', label: 'phpunit.xml' },
    { rel: 'phpunit.xml.dist', label: 'phpunit.xml.dist' },
    { rel: 'Pest.php', label: 'Pest.php' },
    { rel: 'playwright.config.ts', label: 'playwright.config.ts' },
    { rel: 'frontend-spa/playwright.config.ts', label: 'frontend-spa Playwright' },
    { rel: 'frontend-spa/e2e', label: 'frontend-spa e2e specs' },
    { rel: 'frontend-spa', label: 'frontend-spa' },
    { rel: '.github/workflows', label: 'GitHub workflows' },
  ];

  for (const c of candidates) {
    const full = join(root, c.rel);
    if (await exists(full)) {
      verified.push(c.label);
      notes.push({
        path: c.rel,
        action: 'verified',
        note: `${c.label} already present — left unchanged`,
      });
    }
  }
  return { verified, notes };
}

function buildTestPlanMarkdown(input: {
  project: ResolvedProject;
  audit: QaAuditReport;
  recommendedCommand?: string;
}): string {
  const byCategory = new Map<string, QaAuditItem[]>();
  for (const item of input.audit.items) {
    const list = byCategory.get(item.category) ?? [];
    list.push(item);
    byCategory.set(item.category, list);
  }

  const lines = [
    `# QA test plan — ${input.project.name}`,
    '',
    `- Goal: ${input.audit.goal}`,
    `- Project path: \`${input.project.absolutePath}\``,
    `- Specialist: \`qa.verify\``,
    input.recommendedCommand
      ? `- Recommended command: \`${input.recommendedCommand}\``
      : '- Recommended command: (detect after apply / set qaTestCommand)',
    '',
    '## Functional & non-functional matrix',
    '',
  ];

  for (const [category, items] of byCategory) {
    lines.push(`### ${category}`, '');
    for (const item of items) {
      lines.push(
        `- **${item.priority}** \`${item.id}\` — ${item.title}`,
        `  - Check: ${item.check}`,
        `  - Verify: ${item.howToVerify}`,
        '',
      );
    }
  }

  lines.push(
    '## Quick wins',
    '',
    ...input.audit.quickWins.map((q) => `- ${q}`),
    '',
    '_Generated by Umer AI OS `qa.verify` on gate Pass._',
    '',
  );
  return lines.join('\n');
}

function buildReportMarkdown(input: {
  project: ResolvedProject;
  audit: QaAuditReport;
  rationale: string;
  result: QaApplyResult;
}): string {
  const checkLines =
    input.result.checks?.map((c) => `- **${c.status.toUpperCase()}** \`${c.itemId}\`: ${c.evidence}`) ??
    [];
  const runLines =
    input.result.runs?.map((r) => {
      if (r.skipped) return `- **SKIPPED** \`${r.kind}\`: ${r.skipReason ?? r.summary}`;
      return `- **${r.exitCode === 0 ? 'PASS' : 'FAIL'}** \`${r.kind}\`: ${r.summary} (\`${r.command}\`)`;
    }) ?? [];
  const lines = [
    `# QA apply report — ${input.project.name}`,
    '',
    `- Applied at: ${input.result.appliedAt}`,
    `- Goal: ${input.audit.goal}`,
    `- Gate rationale: ${input.rationale}`,
    `- Project path: \`${input.project.absolutePath}\``,
    `- Recommended command: ${input.result.recommendedCommand ?? '(none detected)'}`,
    '',
    '## Suite execution (A/B)',
    '',
    ...(runLines.length ? runLines : ['- (no suites executed — scan-only or UMER_QA_SKIP_RUN=1)']),
    '',
    '## Automated checks (repo scan + run merge)',
    '',
    ...(checkLines.length ? checkLines : ['- (no checks)']),
    '',
    '## File actions',
    '',
    ...input.result.files.map((f) => `- **${f.action}** \`${f.path}\` — ${f.note}`),
    '',
    '## Already verified in repo',
    '',
    ...(input.result.verifiedExisting.length
      ? input.result.verifiedExisting.map((v) => `- ${v}`)
      : ['- (none detected)']),
    '',
    '## Still open after automation',
    '',
    ...(input.result.stillManual.length
      ? input.result.stillManual.map(
          (i) => `- **${i.priority}** ${i.title}: ${i.check} _(verify: ${i.howToVerify})_`,
        )
      : ['- None — all automated checks passed or were patched.']),
    '',
    '## Quick wins from audit',
    '',
    ...input.audit.quickWins.map((q) => `- ${q}`),
    '',
    '_Generated by Umer AI OS `qa.verify` scan→run→evidence on gate Pass._',
    '',
  ];
  return lines.join('\n');
}

function stillManualFromChecks(items: QaAuditItem[], checks: QaCheckResult[]): QaAuditItem[] {
  const byId = new Map(checks.map((c) => [c.itemId, c]));
  return items.filter((item) => {
    const status = byId.get(item.id)?.status;
    return status === 'fail' || status === 'skipped';
  });
}

/**
 * QA apply pipeline:
 * A) scan repo for test/CI signals and evaluate checklist
 * B) write TEST_PLAN.md
 * C) execute allowlisted PHPUnit / Playwright (unless UMER_QA_SKIP_RUN=1)
 * D) merge run results into checks and seal `.umer/qa/`
 */
export async function applyQaToProject(input: {
  project: ResolvedProject;
  audit: QaAuditReport;
  rationale: string;
}): Promise<QaApplyResult> {
  const appliedAt = new Date().toISOString();
  const root = input.project.absolutePath;
  if (!(await exists(root))) {
    throw new Error(`Project path does not exist: ${root}`);
  }

  const outDir = umerQaDir(root);
  const evidenceDir = join(outDir, 'evidence');
  await ensureDir(evidenceDir);

  const { verified, notes } = await verifyExisting(input.project);
  const files: QaApplyFileChange[] = [...notes];

  const signals = await collectQaRepoSignals(root);
  await writeFile(
    join(evidenceDir, 'repo-signals.json'),
    `${JSON.stringify(signals, null, 2)}\n`,
    'utf8',
  );
  files.push({
    path: '.umer/qa/evidence/repo-signals.json',
    action: 'created',
    note: 'Collected automated test / CI signals from the Laragon project',
  });

  let checks = evaluateQaChecks(input.audit.items, signals);
  const recommendedCommand =
    input.project.qaTestCommand?.trim() ||
    signals.detectedCommands[0] ||
    undefined;

  const planRel = join('.umer', 'qa', 'TEST_PLAN.md');
  await writeFile(
    join(root, planRel),
    buildTestPlanMarkdown({
      project: input.project,
      audit: input.audit,
      recommendedCommand,
    }),
    'utf8',
  );
  files.push({
    path: planRel.replace(/\\/g, '/'),
    action: 'created',
    note: 'Functional + non-functional QA test plan from qa.verify checklist',
  });

  const runBundle = await runQaSuites({
    project: input.project,
    signals,
    evidenceDir,
  });
  files.push(...runBundle.files);
  checks = mergeQaRunIntoChecks(checks, runBundle);

  checks = checks.map((c) =>
    c.itemId === 'release-evidence'
      ? {
          ...c,
          status: 'patched',
          evidence: 'Wrote .umer/qa/TEST_PLAN.md + apply/run artifacts on gate Pass',
        }
      : c,
  );

  const stillManual = stillManualFromChecks(input.audit.items, checks);
  const patchedItemIds = ['release-evidence'];

  const resultBase: QaApplyResult = {
    projectId: input.project.projectId,
    absolutePath: root,
    appliedAt,
    files,
    verifiedExisting: verified,
    stillManual,
    summary: '',
    checks,
    signals,
    patchedItemIds,
    recommendedCommand,
    runs: runBundle.runs,
    runBundle,
  };

  const payload = {
    specialistId: 'qa.verify' as const,
    appliedAt,
    projectId: input.project.projectId,
    goal: input.audit.goal,
    rationale: input.rationale,
    verifiedExisting: verified,
    stillManualCount: stillManual.length,
    patchedItemIds,
    recommendedCommand: recommendedCommand ?? null,
    checks,
    signals,
    runs: runBundle.runs,
    runSkippedAll: runBundle.skippedAll,
    runSkipReason: runBundle.skipReason ?? null,
    audit: input.audit,
  };

  const jsonRel = join('.umer', 'qa', 'last-apply.json');
  await writeFile(join(root, jsonRel), `${JSON.stringify(payload, null, 2)}\n`, 'utf8');
  files.push({
    path: jsonRel.replace(/\\/g, '/'),
    action: 'created',
    note: 'Machine-readable QA apply + verify + run record',
  });

  resultBase.files = files;
  const passCount = checks.filter((c) => c.status === 'pass' || c.status === 'patched').length;
  const runPass = runBundle.runs.filter((r) => r.ran && r.exitCode === 0).length;
  const runFail = runBundle.runs.filter((r) => r.ran && r.exitCode !== 0).length;
  resultBase.summary = `QA package for ${input.project.name}: checks pass=${passCount}/${checks.length}, runs pass=${runPass} fail=${runFail}, still open=${stillManual.length}, cmd=${recommendedCommand ?? 'none'}.`;

  const mdRel = join('.umer', 'qa', 'APPLY_REPORT.md');
  await writeFile(
    join(root, mdRel),
    buildReportMarkdown({
      project: input.project,
      audit: input.audit,
      rationale: input.rationale,
      result: resultBase,
    }),
    'utf8',
  );
  files.push({
    path: mdRel.replace(/\\/g, '/'),
    action: 'created',
    note: 'Human-readable QA verify + run report',
  });
  resultBase.files = files;

  return resultBase;
}
