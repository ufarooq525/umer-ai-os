import { access, mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import type { ResolvedProject } from './types.js';
import type { SecurityAuditReport, SecurityFinding } from './security-audit.js';
import { isSafeProjectRelativePath } from './eng-scope.js';
import { ProjectRegistryError } from './errors.js';

export type SecurityApplyFileChange = {
  path: string;
  action: 'created' | 'verified';
  note: string;
};

export type SecurityApplyResult = {
  projectId: string;
  absolutePath: string;
  runId: string;
  appliedAt: string;
  /** Evidence root: `.umer/security/<runId>`. */
  evidenceDir: string;
  files: SecurityApplyFileChange[];
  summary: string;
  findingCount: number;
  forcesGate: boolean;
};

async function exists(path: string): Promise<boolean> {
  try {
    await access(path);
    return true;
  } catch {
    return false;
  }
}

function umerSecurityRunDir(projectRoot: string, runId: string): string {
  return join(projectRoot, '.umer', 'security', runId);
}

function buildFindingsMarkdown(report: SecurityAuditReport): string {
  const lines = [
    `# Security audit — ${report.projectName}`,
    '',
    `- Run: \`${report.runId}\``,
    `- Goal: ${report.goal}`,
    `- Specialist: \`security.review\``,
    `- Forces human gate: ${report.forcesGate ? 'yes (critical/high)' : 'no'}`,
    `- Gate: ${report.gateDecision.reason}`,
    '',
    '## Severity counts',
    '',
    `- critical: ${report.severityCounts.critical}`,
    `- high: ${report.severityCounts.high}`,
    `- medium: ${report.severityCounts.medium}`,
    `- low: ${report.severityCounts.low}`,
    '',
    '## Findings',
    '',
  ];

  if (report.findings.length === 0) {
    lines.push('- None.');
  } else {
    for (const f of report.findings) {
      lines.push(
        `### ${f.severity.toUpperCase()} \`${f.id}\` — ${f.title}`,
        '',
        `- Category: ${f.category}`,
        f.path ? `- Path: \`${f.path}\`` : '- Path: (n/a)',
        `- Detail: ${f.detail}`,
        `- Evidence: ${f.evidence}`,
        `- Remediation: ${f.remediation}`,
        '',
      );
    }
  }

  lines.push(
    '## Quick wins',
    '',
    ...report.quickWins.map((q) => `- ${q}`),
    '',
    '_Report-only — no proposedDiff / auto-fix in security v1._',
    '',
  );
  return lines.join('\n');
}

function buildReportMarkdown(input: {
  project: ResolvedProject;
  report: SecurityAuditReport;
  rationale: string;
  result: SecurityApplyResult;
}): string {
  return [
    `# Security apply report — ${input.project.name}`,
    '',
    `- Applied at: ${input.result.appliedAt}`,
    `- Run: \`${input.result.runId}\``,
    `- Goal: ${input.report.goal}`,
    `- Gate rationale: ${input.rationale}`,
    `- Evidence: \`${input.result.evidenceDir}/\``,
    `- Findings sealed: ${input.result.findingCount}`,
    `- Forces gate was: ${input.result.forcesGate}`,
    '',
    '## File actions',
    '',
    ...input.result.files.map((f) => `- **${f.action}** \`${f.path}\` — ${f.note}`),
    '',
    '_Generated by Umer AI OS `security.review` on gate Pass (evidence seal only — no code mutation)._',
    '',
  ].join('\n');
}

/**
 * Seal a security work package under `.umer/security/<runId>/`.
 *
 * Mirrors QA's evidence layout (report + JSON + evidence/) but never mutates
 * product source — v1 is report-only.
 */
export async function applySecurityToProject(input: {
  project: ResolvedProject;
  report: SecurityAuditReport;
  rationale: string;
}): Promise<SecurityApplyResult> {
  const appliedAt = new Date().toISOString();
  const root = input.project.absolutePath;
  const runId = input.report.runId;

  if (!(await exists(root))) {
    throw new ProjectRegistryError('INVALID_INTAKE', `Project path does not exist: ${root}`);
  }
  if (!/^sec-[A-Za-z0-9._-]+$/.test(runId)) {
    throw new ProjectRegistryError('INVALID_INTAKE', `Unsafe security runId: ${runId}`);
  }

  for (const f of input.report.findings) {
    if (f.path && !isSafeProjectRelativePath(root, f.path)) {
      throw new ProjectRegistryError('INVALID_INTAKE', `Finding path rejected: ${f.path}`);
    }
  }

  const outDir = umerSecurityRunDir(root, runId);
  const evidenceDir = join(outDir, 'evidence');
  await mkdir(evidenceDir, { recursive: true });

  const files: SecurityApplyFileChange[] = [];
  const relBase = `.umer/security/${runId}`;

  await writeFile(join(outDir, 'FINDINGS.md'), buildFindingsMarkdown(input.report), 'utf8');
  files.push({
    path: `${relBase}/FINDINGS.md`,
    action: 'created',
    note: 'Human-readable security findings',
  });

  await writeFile(
    join(evidenceDir, 'findings.json'),
    `${JSON.stringify(
      {
        findings: input.report.findings as SecurityFinding[],
        severityCounts: input.report.severityCounts,
        forcesGate: input.report.forcesGate,
        gateDecision: input.report.gateDecision,
        dependencyCommandsRan: input.report.dependencyCommandsRan,
        dependencyCommandsSkipped: input.report.dependencyCommandsSkipped,
      },
      null,
      2,
    )}\n`,
    'utf8',
  );
  files.push({
    path: `${relBase}/evidence/findings.json`,
    action: 'created',
    note: 'Machine-readable findings',
  });

  const result: SecurityApplyResult = {
    projectId: input.project.projectId,
    absolutePath: root,
    runId,
    appliedAt,
    evidenceDir: relBase,
    files,
    summary: '',
    findingCount: input.report.findings.length,
    forcesGate: input.report.forcesGate,
  };

  const payload = {
    specialistId: 'security.review' as const,
    appliedAt,
    runId,
    projectId: input.project.projectId,
    goal: input.report.goal,
    rationale: input.rationale,
    findingCount: input.report.findings.length,
    severityCounts: input.report.severityCounts,
    forcesGate: input.report.forcesGate,
    gateDecision: input.report.gateDecision,
    proposedDiff: '',
    report: input.report,
  };

  await writeFile(join(outDir, 'last-apply.json'), `${JSON.stringify(payload, null, 2)}\n`, 'utf8');
  files.push({
    path: `${relBase}/last-apply.json`,
    action: 'created',
    note: 'Machine-readable security seal record',
  });

  result.summary = `Security package for ${input.project.name} (${runId}): sealed ${input.report.findings.length} finding(s), forcesGate=${input.report.forcesGate}, evidence=${relBase}/.`;

  await writeFile(
    join(outDir, 'APPLY_REPORT.md'),
    buildReportMarkdown({
      project: input.project,
      report: input.report,
      rationale: input.rationale,
      result,
    }),
    'utf8',
  );
  files.push({
    path: `${relBase}/APPLY_REPORT.md`,
    action: 'created',
    note: 'Human-readable security apply/seal report',
  });
  result.files = files;

  return result;
}
