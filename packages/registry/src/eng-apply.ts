import { access, mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import type { ResolvedProject } from './types.js';
import type { EngDeliveryReport, EngTestPlanItem } from './eng-delivery.js';
import { assertSafeEngRunId } from './eng-scope.js';
import {
  assertEngApplyAllowed,
  engApprovalMode,
  engApprovalRationale,
  type EngApplyApproval,
} from './eng-gate-policy.js';
import { ProjectRegistryError } from './errors.js';
import { applyScopedEdits } from './apply-scoped-edits.js';
import type { EngApplyFileChange, EngApplyResult } from './eng-result-types.js';

export type { EngApplyFileChange, EngApplyResult } from './eng-result-types.js';

async function exists(path: string): Promise<boolean> {
  try {
    await access(path);
    return true;
  } catch {
    return false;
  }
}

function umerEngRunDir(projectRoot: string, runId: string): string {
  return join(projectRoot, '.umer', 'eng', runId);
}

function buildTestPlanMarkdown(input: {
  project: ResolvedProject;
  report: EngDeliveryReport;
}): string {
  const lines = [
    `# Eng test plan — ${input.project.name}`,
    '',
    `- Run ID: \`${input.report.runId}\``,
    `- Goal: ${input.report.goal}`,
    `- Type: ${input.report.type}`,
    `- Project path: \`${input.project.absolutePath}\``,
    `- Specialist: \`eng.app-delivery\``,
    input.report.recommendedCommand
      ? `- Recommended command: \`${input.report.recommendedCommand}\``
      : '- Recommended command: (none detected)',
    `- Staged testsRan=${input.report.testsRan} testsPassed=${input.report.testsPassed}`,
    '',
    '## Test plan',
    '',
  ];

  for (const item of input.report.testPlan) {
    lines.push(
      `- **${item.priority}** \`${item.id}\` (${item.category}) — ${item.title}`,
      `  - Check: ${item.check}`,
      `  - Verify: ${item.howToVerify}`,
      '',
    );
  }

  lines.push(
    '## Rationale',
    '',
    input.report.rationale,
    '',
    '_Generated by Umer AI OS `eng.app-delivery` on apply._',
    '',
  );
  return lines.join('\n');
}

function buildReportMarkdown(input: {
  project: ResolvedProject;
  report: EngDeliveryReport;
  rationale: string;
  result: EngApplyResult;
}): string {
  const runLines =
    input.result.runs?.map((r) => {
      if (r.skipped) return `- **SKIPPED** \`${r.kind}\`: ${r.skipReason ?? r.summary}`;
      return `- **${r.exitCode === 0 ? 'PASS' : 'FAIL'}** \`${r.kind}\`: ${r.summary} (\`${r.command}\`)`;
    }) ?? [];
  const evidenceLines =
    input.report.stagedEvidence.length > 0
      ? input.report.stagedEvidence.map(
          (e) => `- \`.umer/eng/${input.result.runId}/evidence/${e.name}\``,
        )
      : ['- (no staged suite evidence captured)'];
  const lines = [
    `# Eng apply report — ${input.project.name}`,
    '',
    `- Applied at: ${input.result.appliedAt}`,
    `- Run ID: \`${input.result.runId}\``,
    `- Goal: ${input.report.goal}`,
    `- Gate rationale: ${input.rationale}`,
    `- Project path: \`${input.project.absolutePath}\``,
    `- Evidence: \`.umer/eng/${input.result.runId}/\``,
    `- Diff applied: ${input.result.diffApplied}`,
    '',
    '## Staged suite results (from work package)',
    '',
    ...(runLines.length ? runLines : ['- (no suites ran against staging)']),
    '',
    '## Sealed suite evidence',
    '',
    ...evidenceLines,
    '',
    '## File actions',
    '',
    ...input.result.files.map((f) => `- **${f.action}** \`${f.path}\` — ${f.note}`),
    '',
    '## Changed source files',
    '',
    ...(input.result.changedFiles.length
      ? input.result.changedFiles.map((p) => `- \`${p}\``)
      : ['- (none)']),
    '',
    '## Still manual',
    '',
    ...(input.result.stillManual.length
      ? input.result.stillManual.map(
          (i) => `- **${i.priority}** ${i.title}: ${i.check}`,
        )
      : ['- None flagged']),
    '',
    '_Generated by Umer AI OS `eng.app-delivery` on apply._',
    '',
  ];
  return lines.join('\n');
}

function stillManualItems(report: EngDeliveryReport): EngTestPlanItem[] {
  return report.testPlan.filter(
    (i) => i.category === 'manual' || (i.id === 'eng-regression-suite' && !report.testsPassed),
  );
}

/**
 * Apply an approved eng work package to the real Laragon project and seal
 * evidence under `.umer/eng/<runId>/`.
 *
 * Uses the structured change-set / resolved edits — never a free-form patch parser.
 * Manual-scoping packages and ineligible auto mode are rejected (fail closed).
 */
export async function applyEngToProject(input: {
  project: ResolvedProject;
  report: EngDeliveryReport;
  /** Explicit human-gate or auto approval — required at the mutation boundary. */
  approval: EngApplyApproval;
}): Promise<EngApplyResult> {
  const mode = engApprovalMode(input.approval);
  const rationale = engApprovalRationale(input.approval);

  assertEngApplyAllowed({
    category: input.project.category,
    autoApplyEng: input.project.autoApplyEng === true,
    approval: input.approval,
    package: input.report,
  });

  const appliedAt = new Date().toISOString();
  const root = input.project.absolutePath;
  const runId = assertSafeEngRunId(input.report.runId);

  if (!(await exists(root))) {
    throw new ProjectRegistryError('ENG_APPLY_BLOCKED', `Project path does not exist: ${root}`);
  }

  const scoped = await applyScopedEdits({
    root,
    edits: input.report.edits,
    blockCode: 'ENG_APPLY_BLOCKED',
  });

  const outDir = umerEngRunDir(root, runId);
  const evidenceDir = join(outDir, 'evidence');
  await mkdir(evidenceDir, { recursive: true });

  const files: EngApplyFileChange[] = [...scoped.files];
  const changedFiles = scoped.changedFiles;

  // Seal captured staging suite evidence into the real project evidence dir.
  for (const artifact of input.report.stagedEvidence) {
    if (!/^[A-Za-z0-9._-]+$/.test(artifact.name)) continue;
    const rel = `.umer/eng/${runId}/evidence/${artifact.name}`;
    await writeFile(join(evidenceDir, artifact.name), artifact.content, 'utf8');
    files.push({
      path: rel,
      action: 'created',
      note: 'Staged suite evidence sealed from work package',
    });
  }

  const proposedRel = join('.umer', 'eng', runId, 'PROPOSED_DIFF.patch').replace(/\\/g, '/');
  await writeFile(join(outDir, 'PROPOSED_DIFF.patch'), input.report.proposedDiff || '(empty)\n', 'utf8');
  files.push({
    path: proposedRel,
    action: 'created',
    note: 'Human-readable proposed diff sealed for audit',
  });

  const planRel = join('.umer', 'eng', runId, 'TEST_PLAN.md').replace(/\\/g, '/');
  await writeFile(
    join(outDir, 'TEST_PLAN.md'),
    buildTestPlanMarkdown({ project: input.project, report: input.report }),
    'utf8',
  );
  files.push({
    path: planRel,
    action: 'created',
    note: 'Eng test plan from eng.app-delivery',
  });

  const stillManual = stillManualItems(input.report);
  const resultBase: EngApplyResult = {
    projectId: input.project.projectId,
    absolutePath: root,
    runId,
    appliedAt,
    evidenceDir: `.umer/eng/${runId}`,
    files,
    changedFiles,
    verifiedExisting: [],
    stillManual,
    summary: '',
    diffApplied: true,
    reverted: false,
    signals: input.report.signals,
    recommendedCommand: input.report.recommendedCommand,
    runs: input.report.runs,
    runBundle: input.report.runBundle,
  };

  const payload = {
    specialistId: 'eng.app-delivery' as const,
    appliedAt,
    runId,
    projectId: input.project.projectId,
    goal: input.report.goal,
    rationale,
    approval: input.approval,
    mode,
    changedFiles,
    testsRan: input.report.testsRan,
    testsPassed: input.report.testsPassed,
    editStats: input.report.editStats,
    changeSet: input.report.changeSet,
    runs: input.report.runs,
    stagedEvidenceNames: input.report.stagedEvidence.map((e) => e.name),
    report: input.report,
  };

  const jsonRel = join('.umer', 'eng', runId, 'last-apply.json').replace(/\\/g, '/');
  await writeFile(join(outDir, 'last-apply.json'), `${JSON.stringify(payload, null, 2)}\n`, 'utf8');
  files.push({
    path: jsonRel,
    action: 'created',
    note: 'Machine-readable eng apply record',
  });

  resultBase.summary = `Eng package for ${input.project.name} (${runId}): applied ${changedFiles.length} file(s), testsRan=${input.report.testsRan} testsPassed=${input.report.testsPassed}, evidence=.umer/eng/${runId}/.`;

  const mdRel = join('.umer', 'eng', runId, 'APPLY_REPORT.md').replace(/\\/g, '/');
  await writeFile(
    join(outDir, 'APPLY_REPORT.md'),
    buildReportMarkdown({
      project: input.project,
      report: input.report,
      rationale,
      result: resultBase,
    }),
    'utf8',
  );
  files.push({
    path: mdRel,
    action: 'created',
    note: 'Human-readable eng apply report',
  });
  resultBase.files = files;

  return resultBase;
}
