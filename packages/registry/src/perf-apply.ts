import { access, mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import type { ResolvedProject } from './types.js';
import type { PerfAuditReport } from './perf-audit.js';
import { ProjectRegistryError } from './errors.js';

export type PerfApplyFileChange = {
  path: string;
  action: 'created' | 'verified';
  note: string;
};

export type PerfApplyResult = {
  projectId: string;
  absolutePath: string;
  runId: string;
  appliedAt: string;
  evidenceDir: string;
  files: PerfApplyFileChange[];
  summary: string;
  findingCount: number;
  forcesGate: boolean;
};

async function exists(path: string): Promise<boolean> {
  try {
    await access(path);
    return true;
  } catch {
    return false;
  }
}

function buildFindingsMarkdown(report: PerfAuditReport): string {
  const lines = [
    `# Performance audit — ${report.projectName}`,
    '',
    `- Run: \`${report.runId}\``,
    `- Goal: ${report.goal}`,
    `- Specialist: \`perf.optimize\``,
    `- Target URL: ${report.targetUrl ?? '(not configured)'}`,
    `- Lighthouse: ${report.lighthouseNote}`,
    `- Performance score: ${
      report.metrics.performanceScore === null
        ? 'n/a'
        : `${Math.round(report.metrics.performanceScore * 100)}/100`
    }`,
    `- LCP: ${report.metrics.lcpMs === null ? 'n/a' : `${report.metrics.lcpMs}ms`}`,
    `- CLS: ${report.metrics.cls ?? 'n/a'}`,
    `- INP: ${report.metrics.inpMs === null ? 'n/a' : `${report.metrics.inpMs}ms`}`,
    `- Max potential FID: ${
      report.metrics.fidMs === null ? 'n/a' : `${report.metrics.fidMs}ms`
    }`,
    `- Forces human gate: ${report.forcesGate ? 'yes (critical/high)' : 'no'}`,
    `- Gate: ${report.gateDecision.reason}`,
    '',
    '## Severity counts',
    '',
    `- critical: ${report.severityCounts.critical}`,
    `- high: ${report.severityCounts.high}`,
    `- medium: ${report.severityCounts.medium}`,
    `- low: ${report.severityCounts.low}`,
    '',
    '## Findings',
    '',
  ];

  if (report.findings.length === 0) {
    lines.push('- None.');
  } else {
    for (const finding of report.findings) {
      lines.push(
        `### ${finding.severity.toUpperCase()} \`${finding.id}\` — ${finding.title}`,
        '',
        `- Category: ${finding.category}`,
        `- Metric: ${finding.metric}`,
        `- Detail: ${finding.detail}`,
        `- Evidence: ${finding.evidence}`,
        `- Remediation: ${finding.remediation}`,
        '',
      );
    }
  }

  lines.push(
    '## Quick wins',
    '',
    ...report.quickWins.map((quickWin) => `- ${quickWin}`),
    '',
    '_Report-only — no proposedDiff / auto-fix in perf v1._',
    '',
  );
  return lines.join('\n');
}

function buildApplyReport(input: {
  project: ResolvedProject;
  report: PerfAuditReport;
  rationale: string;
  result: PerfApplyResult;
}): string {
  return [
    `# Performance apply report — ${input.project.name}`,
    '',
    `- Applied at: ${input.result.appliedAt}`,
    `- Run: \`${input.result.runId}\``,
    `- Goal: ${input.report.goal}`,
    `- Gate rationale: ${input.rationale}`,
    `- Evidence: \`${input.result.evidenceDir}/\``,
    `- Findings sealed: ${input.result.findingCount}`,
    `- Forces gate was: ${input.result.forcesGate}`,
    '',
    '## File actions',
    '',
    ...input.result.files.map(
      (file) => `- **${file.action}** \`${file.path}\` — ${file.note}`,
    ),
    '',
    '_Generated by Umer AI OS `perf.optimize` on gate Pass (evidence seal only — no code mutation)._',
    '',
  ].join('\n');
}

/** Seal a perf work package after gate Pass; never mutate application source. */
export async function applyPerfToProject(input: {
  project: ResolvedProject;
  report: PerfAuditReport;
  rationale: string;
}): Promise<PerfApplyResult> {
  const root = input.project.absolutePath;
  const runId = input.report.runId;
  const appliedAt = new Date().toISOString();

  if (!(await exists(root))) {
    throw new ProjectRegistryError('INVALID_INTAKE', `Project path does not exist: ${root}`);
  }
  if (!/^perf-[A-Za-z0-9._-]+$/.test(runId)) {
    throw new ProjectRegistryError('INVALID_INTAKE', `Unsafe perf runId: ${runId}`);
  }

  const outDir = join(root, '.umer', 'perf', runId);
  const evidenceDir = join(outDir, 'evidence');
  const relBase = `.umer/perf/${runId}`;
  await mkdir(evidenceDir, { recursive: true });

  const files: PerfApplyFileChange[] = [];
  await writeFile(join(outDir, 'FINDINGS.md'), buildFindingsMarkdown(input.report), 'utf8');
  files.push({
    path: `${relBase}/FINDINGS.md`,
    action: 'created',
    note: 'Human-readable performance findings',
  });

  await writeFile(
    join(evidenceDir, 'findings.json'),
    `${JSON.stringify(
      {
        findings: input.report.findings,
        metrics: input.report.metrics,
        severityCounts: input.report.severityCounts,
        forcesGate: input.report.forcesGate,
        gateDecision: input.report.gateDecision,
        targetUrl: input.report.targetUrl,
        lighthouseRan: input.report.lighthouseRan,
        lighthouseNote: input.report.lighthouseNote,
      },
      null,
      2,
    )}\n`,
    'utf8',
  );
  files.push({
    path: `${relBase}/evidence/findings.json`,
    action: 'created',
    note: 'Machine-readable findings and metrics',
  });

  if (input.report.lighthouseReport) {
    await writeFile(
      join(evidenceDir, 'lighthouse.json'),
      `${JSON.stringify(input.report.lighthouseReport, null, 2)}\n`,
      'utf8',
    );
    files.push({
      path: `${relBase}/evidence/lighthouse.json`,
      action: 'created',
      note: 'Raw Lighthouse performance report captured during audit',
    });
  }

  const result: PerfApplyResult = {
    projectId: input.project.projectId,
    absolutePath: root,
    runId,
    appliedAt,
    evidenceDir: relBase,
    files,
    summary: '',
    findingCount: input.report.findings.length,
    forcesGate: input.report.forcesGate,
  };

  const reportWithoutRawLighthouse = {
    ...input.report,
    lighthouseReport: undefined,
  };
  await writeFile(
    join(outDir, 'last-apply.json'),
    `${JSON.stringify(
      {
        specialistId: 'perf.optimize',
        appliedAt,
        runId,
        projectId: input.project.projectId,
        goal: input.report.goal,
        rationale: input.rationale,
        findingCount: input.report.findings.length,
        severityCounts: input.report.severityCounts,
        forcesGate: input.report.forcesGate,
        gateDecision: input.report.gateDecision,
        proposedDiff: '',
        report: reportWithoutRawLighthouse,
      },
      null,
      2,
    )}\n`,
    'utf8',
  );
  files.push({
    path: `${relBase}/last-apply.json`,
    action: 'created',
    note: 'Machine-readable performance seal record',
  });

  result.summary = `Performance package for ${input.project.name} (${runId}): sealed ${input.report.findings.length} finding(s), forcesGate=${input.report.forcesGate}, evidence=${relBase}/.`;

  await writeFile(
    join(outDir, 'APPLY_REPORT.md'),
    buildApplyReport({
      project: input.project,
      report: input.report,
      rationale: input.rationale,
      result,
    }),
    'utf8',
  );
  files.push({
    path: `${relBase}/APPLY_REPORT.md`,
    action: 'created',
    note: 'Human-readable performance evidence seal report',
  });

  return result;
}
