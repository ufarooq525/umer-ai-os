import { join } from 'node:path';
import type { ResolvedProject } from './types.js';
import type { SeoAuditItem, SeoAuditReport } from './seo-audit.js';
import { resolveSeoProbeUrls, pickReachableSeoUrl } from './seo-urls.js';
import {
  enrichWithRobotsSitemap,
  evaluateSeoChecks,
  extractPageSeoSignals,
  type SeoCheckResult,
} from './seo-verify.js';
import { runLighthouseEvidence } from './seo-lighthouse.js';
import { applySafeSeoPatches } from './seo-patch.js';
import { applyScopedEdits } from './apply-scoped-edits.js';
import { SEO_FIX_EVIDENCE_PATHS } from './seo-diff.js';
import type { SeoApplyFileChange, SeoApplyResult } from './seo-result-types.js';

export type { SeoApplyFileChange, SeoApplyResult } from './seo-result-types.js';

async function exists(path: string): Promise<boolean> {
  try {
    await access(path);
    return true;
  } catch {
    return false;
  }
}

async function ensureDir(path: string): Promise<void> {
  await mkdir(path, { recursive: true });
}

function umerSeoDir(projectRoot: string): string {
  return join(projectRoot, '.umer', 'seo');
}

function hasSeoChangeSet(audit: SeoAuditReport): boolean {
  return (
    (audit.edits?.length ?? 0) > 0 &&
    Boolean(audit.proposedDiff?.trim()) &&
    (audit.changeSet?.length ?? 0) > 0
  );
}

async function verifyExisting(
  project: ResolvedProject,
): Promise<{ verified: string[]; notes: SeoApplyFileChange[] }> {
  const verified: string[] = [];
  const notes: SeoApplyFileChange[] = [];
  const root = project.absolutePath;

  const candidates: Array<{ rel: string; label: string }> = [
    { rel: 'public/robots.txt', label: 'robots.txt' },
    { rel: 'src/app/robots.ts', label: 'Next robots.ts' },
    { rel: 'public/sitemap.xml', label: 'sitemap.xml' },
    { rel: 'src/app/sitemap.ts', label: 'Next sitemap.ts' },
    { rel: 'src/lib/seo.ts', label: 'seo helper module' },
    { rel: 'index.html', label: 'index.html meta shell' },
  ];

  for (const c of candidates) {
    const full = join(root, c.rel);
    if (await exists(full)) {
      verified.push(c.label);
      notes.push({
        path: c.rel,
        action: 'verified',
        note: `${c.label} already present — left unchanged`,
      });
    }
  }
  return { verified, notes };
}

function buildReportMarkdown(input: {
  project: ResolvedProject;
  audit: SeoAuditReport;
  rationale: string;
  result: SeoApplyResult;
}): string {
  const checkLines =
    input.result.checks?.map((c) => `- **${c.status.toUpperCase()}** \`${c.itemId}\`: ${c.evidence}`) ??
    [];
  const lines = [
    `# SEO apply report — ${input.project.name}`,
    '',
    `- Applied at: ${input.result.appliedAt}`,
    `- Goal: ${input.audit.goal}`,
    `- Gate rationale: ${input.rationale}`,
    `- Project path: \`${input.project.absolutePath}\``,
    `- Probe URL: ${input.result.probeUrl ?? '(none reachable)'}`,
    `- Lighthouse: ${input.result.lighthouse?.note ?? 'n/a'}`,
    input.result.changeSetApplied
      ? '- Source changes: work-package change-set (scoped apply)'
      : '- Source changes: legacy applySafeSeoPatches (no proposedDiff)',
    '',
    '## Automated checks (A)',
    '',
    ...(checkLines.length ? checkLines : ['- (no checks)']),
    '',
    '## File actions (B patches + package)',
    '',
    ...input.result.files.map((f) => `- **${f.action}** \`${f.path}\` — ${f.note}`),
    '',
    '## Already verified in repo',
    '',
    ...(input.result.verifiedExisting.length
      ? input.result.verifiedExisting.map((v) => `- ${v}`)
      : ['- (none detected)']),
    '',
    '## Still open after automation',
    '',
    ...(input.result.stillManual.length
      ? input.result.stillManual.map(
          (i) => `- **${i.priority}** ${i.title}: ${i.check} _(verify: ${i.howToVerify})_`,
        )
      : ['- None — all automated checks passed or were patched.']),
    '',
    '## Quick wins from audit',
    '',
    ...input.audit.quickWins.map((q) => `- ${q}`),
    '',
    input.result.changeSetApplied
      ? '_Generated by Umer AI OS `seo.audit` verify→scoped change-set apply on gate Pass._'
      : '_Generated by Umer AI OS `seo.audit` verify→patch→re-verify on gate Pass._',
    '',
  ];
  return lines.join('\n');
}

function stillManualFromChecks(
  items: SeoAuditItem[],
  checks: SeoCheckResult[],
): SeoAuditItem[] {
  const byId = new Map(checks.map((c) => [c.itemId, c]));
  return items.filter((item) => {
    const status = byId.get(item.id)?.status;
    return status === 'fail' || status === 'skipped';
  });
}

/**
 * Full SEO apply pipeline (gate Pass only — no auto-apply, even if autoApplyEng is set):
 * A) scrape + evaluate checklist + optional Lighthouse
 * B) if work package has a proposed change-set → shared {@link applyScopedEdits}
 *    else → legacy {@link applySafeSeoPatches} (report-only / no proposal path)
 * Then seal `.umer/seo/` evidence (including PROPOSED_DIFF when change-set applied).
 */
export async function applySeoToProject(input: {
  project: ResolvedProject;
  audit: SeoAuditReport;
  rationale: string;
}): Promise<SeoApplyResult> {
  const appliedAt = new Date().toISOString();
  const root = input.project.absolutePath;
  if (!(await exists(root))) {
    throw new Error(`Project path does not exist: ${root}`);
  }

  const outDir = umerSeoDir(root);
  const evidenceDir = join(outDir, 'evidence');
  await ensureDir(evidenceDir);

  const { verified, notes } = await verifyExisting(input.project);
  const files: SeoApplyFileChange[] = [...notes];

  const candidates = resolveSeoProbeUrls(input.project);
  const probed = await pickReachableSeoUrl(candidates);
  let checks: SeoCheckResult[] = [];
  let lighthouse = await runLighthouseEvidence({
    url: probed?.finalUrl ?? candidates[0] ?? '',
    evidenceDir,
    enabled: Boolean(probed),
  });

  if (probed) {
    let signals = extractPageSeoSignals(probed.html, probed.finalUrl);
    signals = await enrichWithRobotsSitemap(signals);
    await writeFile(
      join(evidenceDir, 'page-signals.json'),
      `${JSON.stringify({ probe: probed.url, finalUrl: probed.finalUrl, signals }, null, 2)}\n`,
      'utf8',
    );
    files.push({
      path: '.umer/seo/evidence/page-signals.json',
      action: 'created',
      note: 'Scraped on-page SEO signals',
    });
    checks = evaluateSeoChecks(input.audit.items, signals, {
      lighthouse: {
        lcpOk: lighthouse.lcpOk,
        clsOk: lighthouse.clsOk,
        note: lighthouse.note,
      },
    });
  } else {
    checks = evaluateSeoChecks(input.audit.items, null);
  }

  if (lighthouse.ran && lighthouse.reportPath) {
    files.push({
      path: '.umer/seo/evidence/lighthouse.json',
      action: 'created',
      note: lighthouse.note,
    });
    try {
      const raw = await readFile(lighthouse.reportPath, 'utf8');
      await writeFile(join(evidenceDir, 'lighthouse.json'), raw, 'utf8');
    } catch {
      /* ignore copy failure */
    }
  }

  let patchedItemIds: string[] = [];
  let changeSetApplied = false;

  if (hasSeoChangeSet(input.audit)) {
    const scoped = await applyScopedEdits({
      root,
      edits: input.audit.edits!,
      blockCode: 'SEO_APPLY_BLOCKED',
    });
    files.push(...scoped.files);
    patchedItemIds = [...(input.audit.fixableItemIds ?? [])];
    changeSetApplied = true;

    await writeFile(
      join(outDir, 'PROPOSED_DIFF.patch'),
      input.audit.proposedDiff || '(empty)\n',
      'utf8',
    );
    files.push({
      path: SEO_FIX_EVIDENCE_PATHS.proposedDiff,
      action: 'created',
      note: 'Human-reviewed proposedDiff sealed on gate Pass',
    });

    await writeFile(
      join(evidenceDir, 'fix-change-set.json'),
      `${JSON.stringify(input.audit.changeSet, null, 2)}\n`,
      'utf8',
    );
    files.push({
      path: SEO_FIX_EVIDENCE_PATHS.changeSet,
      action: 'created',
      note: 'Structured change-set applied via shared scoped-apply',
    });

    await writeFile(
      join(evidenceDir, 'fix-proposal.json'),
      `${JSON.stringify(
        {
          fixableItemIds: input.audit.fixableItemIds ?? [],
          fixSkipped: input.audit.fixSkipped ?? [],
          fixEditStats: input.audit.fixEditStats ?? null,
          changedFiles: scoped.changedFiles,
        },
        null,
        2,
      )}\n`,
      'utf8',
    );
    files.push({
      path: SEO_FIX_EVIDENCE_PATHS.proposalMeta,
      action: 'created',
      note: 'Fix proposal metadata',
    });

    for (const id of patchedItemIds) {
      checks = checks.map((c) =>
        c.itemId === id
          ? {
              ...c,
              status: 'patched',
              evidence: `${c.evidence} · applied from work-package change-set`,
            }
          : c,
      );
    }
  } else {
    const patch = await applySafeSeoPatches({ project: input.project, checks });
    files.push(...patch.files);
    patchedItemIds = patch.patchedItemIds;

    if (probed && patch.patchedItemIds.length > 0) {
      for (const id of patch.patchedItemIds) {
        checks = checks.map((c) =>
          c.itemId === id
            ? { ...c, status: 'patched', evidence: `${c.evidence} · auto-patched in repo` }
            : c,
        );
      }
    }
  }

  const stillManual = stillManualFromChecks(input.audit.items, checks);

  const resultBase: SeoApplyResult = {
    projectId: input.project.projectId,
    absolutePath: root,
    appliedAt,
    files,
    verifiedExisting: verified,
    stillManual,
    summary: '',
    probeUrl: probed?.finalUrl,
    checks,
    lighthouse,
    patchedItemIds,
    changeSetApplied,
  };

  const payload = {
    specialistId: 'seo.audit' as const,
    appliedAt,
    projectId: input.project.projectId,
    goal: input.audit.goal,
    rationale: input.rationale,
    probeUrl: probed?.finalUrl ?? null,
    verifiedExisting: verified,
    stillManualCount: stillManual.length,
    patchedItemIds,
    changeSetApplied,
    checks,
    lighthouse,
    audit: input.audit,
  };

  const jsonRel = join('.umer', 'seo', 'last-apply.json');
  await writeFile(join(root, jsonRel), `${JSON.stringify(payload, null, 2)}\n`, 'utf8');
  files.push({
    path: jsonRel.replace(/\\/g, '/'),
    action: 'created',
    note: 'Machine-readable apply + verify record',
  });

  resultBase.files = files;
  resultBase.summary = changeSetApplied
    ? `SEO change-set apply for ${input.project.name}: probe=${probed?.finalUrl ?? 'none'}, checks pass=${checks.filter((c) => c.status === 'pass' || c.status === 'patched').length}/${checks.length}, change-set files=${input.audit.edits?.length ?? 0}, still open=${stillManual.length}.`
    : `SEO A+B for ${input.project.name}: probe=${probed?.finalUrl ?? 'none'}, checks pass=${checks.filter((c) => c.status === 'pass' || c.status === 'patched').length}/${checks.length}, patches=${patchedItemIds.length}, still open=${stillManual.length}.`;

  const mdRel = join('.umer', 'seo', 'APPLY_REPORT.md');
  await writeFile(
    join(root, mdRel),
    buildReportMarkdown({
      project: input.project,
      audit: input.audit,
      rationale: input.rationale,
      result: resultBase,
    }),
    'utf8',
  );
  files.push({
    path: mdRel.replace(/\\/g, '/'),
    action: 'created',
    note: 'Human-readable verify + patch report',
  });
  resultBase.files = files;

  return resultBase;
}
