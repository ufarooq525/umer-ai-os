import { access, mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import type { ResolvedProject } from './types.js';
import type { UxAuditItem, UxAuditReport } from './ux-audit.js';
import { ProjectRegistryError } from './errors.js';

export type UxApplyFileChange = {
  path: string;
  action: 'created' | 'verified';
  note: string;
};

export type UxApplyResult = {
  projectId: string;
  absolutePath: string;
  runId: string;
  appliedAt: string;
  /** Evidence root: `.umer/ux/<runId>`. */
  evidenceDir: string;
  files: UxApplyFileChange[];
  summary: string;
  itemCount: number;
};

async function exists(path: string): Promise<boolean> {
  try {
    await access(path);
    return true;
  } catch {
    return false;
  }
}

function buildFindingsMarkdown(report: UxAuditReport): string {
  const byCategory = new Map<string, UxAuditItem[]>();
  for (const item of report.items) {
    const list = byCategory.get(item.category) ?? [];
    list.push(item);
    list.sort((a, b) => a.priority.localeCompare(b.priority));
    byCategory.set(item.category, list);
  }

  const lines = [
    `# UX design audit — ${report.projectName}`,
    '',
    `- Run: \`${report.runId}\``,
    `- Goal: ${report.goal}`,
    `- Specialist: \`ux.design\``,
    `- Items: ${report.items.length}`,
    `- P0: ${report.items.filter((i) => i.priority === 'P0').length}`,
    `- P1: ${report.items.filter((i) => i.priority === 'P1').length}`,
    `- P2: ${report.items.filter((i) => i.priority === 'P2').length}`,
    '',
    '## Checklist by category',
    '',
  ];

  for (const [category, items] of byCategory) {
    lines.push(`### ${category}`, '');
    for (const item of items) {
      lines.push(
        `- **${item.priority}** \`${item.id}\` — ${item.title}`,
        `  - Check: ${item.check}`,
        `  - Verify: ${item.howToVerify}`,
        '',
      );
    }
  }

  lines.push(
    '## Quick wins',
    '',
    ...report.quickWins.map((q) => `- ${q}`),
    '',
    '## Next actions',
    '',
    ...report.nextActions.map((a) => `- ${a}`),
    '',
    '_Report-only — no proposedDiff / auto-apply of product UI in UX v1._',
    '',
  );
  return lines.join('\n');
}

function buildApplyReport(input: {
  project: ResolvedProject;
  report: UxAuditReport;
  rationale: string;
  result: UxApplyResult;
}): string {
  return [
    `# UX apply report — ${input.project.name}`,
    '',
    `- Applied at: ${input.result.appliedAt}`,
    `- Run: \`${input.result.runId}\``,
    `- Goal: ${input.report.goal}`,
    `- Gate rationale: ${input.rationale}`,
    `- Evidence: \`${input.result.evidenceDir}/\``,
    `- Checklist items sealed: ${input.result.itemCount}`,
    '',
    '## File actions',
    '',
    ...input.result.files.map(
      (file) => `- **${file.action}** \`${file.path}\` — ${file.note}`,
    ),
    '',
    '_Generated by Umer AI OS `ux.design` on gate Pass (evidence seal only — no product UI mutation)._',
    '',
    'Handoff approved improvements to `eng.app-delivery` as a separate intake.',
    '',
  ].join('\n');
}

/** Seal a UX work package after gate Pass; never mutate application source. */
export async function applyUxToProject(input: {
  project: ResolvedProject;
  report: UxAuditReport;
  rationale: string;
}): Promise<UxApplyResult> {
  const root = input.project.absolutePath;
  const runId = input.report.runId;
  const appliedAt = new Date().toISOString();

  if (!(await exists(root))) {
    throw new ProjectRegistryError('INVALID_INTAKE', `Project path does not exist: ${root}`);
  }
  if (!/^ux-[A-Za-z0-9._-]+$/.test(runId)) {
    throw new ProjectRegistryError('INVALID_INTAKE', `Unsafe ux runId: ${runId}`);
  }

  const outDir = join(root, '.umer', 'ux', runId);
  const relBase = `.umer/ux/${runId}`;
  await mkdir(outDir, { recursive: true });

  const files: UxApplyFileChange[] = [];
  await writeFile(join(outDir, 'FINDINGS.md'), buildFindingsMarkdown(input.report), 'utf8');
  files.push({
    path: `${relBase}/FINDINGS.md`,
    action: 'created',
    note: 'Human-readable UX checklist findings',
  });

  const result: UxApplyResult = {
    projectId: input.project.projectId,
    absolutePath: root,
    runId,
    appliedAt,
    evidenceDir: relBase,
    files,
    summary: '',
    itemCount: input.report.items.length,
  };

  await writeFile(
    join(outDir, 'last-apply.json'),
    `${JSON.stringify(
      {
        specialistId: 'ux.design',
        appliedAt,
        runId,
        projectId: input.project.projectId,
        goal: input.report.goal,
        rationale: input.rationale,
        itemCount: input.report.items.length,
        proposedDiff: '',
        report: input.report,
      },
      null,
      2,
    )}\n`,
    'utf8',
  );
  files.push({
    path: `${relBase}/last-apply.json`,
    action: 'created',
    note: 'Machine-readable UX seal record',
  });

  result.summary = `UX package for ${input.project.name} (${runId}): sealed ${input.report.items.length} checklist item(s), evidence=${relBase}/.`;

  await writeFile(
    join(outDir, 'APPLY_REPORT.md'),
    buildApplyReport({
      project: input.project,
      report: input.report,
      rationale: input.rationale,
      result,
    }),
    'utf8',
  );
  files.push({
    path: `${relBase}/APPLY_REPORT.md`,
    action: 'created',
    note: 'Human-readable UX evidence seal report',
  });

  result.files = files;
  return result;
}
